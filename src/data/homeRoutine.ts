// Ежедневный график по «Расписанию домашних дел — версия 2»: 20 + 20 + 40 + 20 + 20 = до 120 минут
export interface DailyBlock {
  id: string;
  icon: string;
  title: string;
  minutes: number;
  items: RoutineItem[];
}

const di = (prefix: string, rows: [string, string?][]): RoutineItem[] =>
  rows.map(([title, hint], i) => ({ id: `${prefix}-${i}`, icon: '', title, hint }));


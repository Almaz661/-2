let n = 0;
const i = (sector: MapSector, level: MapLevel, title: string, freq: string, intervalDays: number, fromScheme = false, needs?: Need[]): MapItem => ({
  id: `${sector}-${level}-${++n}`,
  sector,
  level,
  title,
  freq,
  intervalDays,
  fromScheme,
  needs,
});


// «Карта уборки»: схема владельца (4 сектора × 3 уровня уборки) + дополнения до полного списка.
// Уровни: поддерживающая (каждый день), подробная (раз в 1–2 недели), редкая (раз в месяц — полгода).
// intervalDays — через сколько дней пункт снова «пора»; freq — как написано на схеме.
import type { Need } from '../utils/homeProfile';

export type MapSector = 'floor' | 'above' | 'bath' | 'kitchen';
export type MapLevel = 'support' | 'detailed' | 'rare';

export interface MapItem {
  id: string;
  sector: MapSector;
  level: MapLevel;
  title: string;
  freq: string;
  intervalDays: number;
  /** true — пункт со схемы владельца, false — дополнение */
  fromScheme: boolean;
  needs?: Need[];
}

